import { expect, test, type Page } from '@playwright/test'
import { requestRecommendations } from './helpers'

const password = 'Test-local-password-123'
async function register(page: Page, prefix: string) {
  const username = `${prefix}_${Date.now()}`
  await page.goto('/')
  await page.getByRole('button', { name: 'Нет аккаунта? Зарегистрироваться' }).click()
  await page.getByLabel('Логин', { exact: true }).fill(username)
  await page.getByLabel('Пароль', { exact: true }).fill(password)
  await page.getByLabel('Подтвердите пароль', { exact: true }).fill(password)
  await page.getByRole('button', { name: 'Создать аккаунт', exact: true }).click()
  await expect(page.getByRole('heading', { name: 'Что вам нравится?' })).toBeVisible()
  return username
}
async function onboard(page: Page) {
  await page.getByRole('button', { name: 'Использовать мой стартовый вкус' }).click()
  await expect(page.getByRole('button', { name: 'Сохранить вкус и продолжить' })).toBeEnabled()
  await page.getByRole('button', { name: 'Сохранить вкус и продолжить' }).click()
  await expect(page.getByRole('heading', { name: 'С чего начнём слушать?' })).toBeVisible()
}
test('registration, recommendations, explicit feedback, persistence and account isolation', async ({ page, browser }) => {
  const username = await register(page, 'music')
  await onboard(page)
  await expect(page.getByRole('button', { name: 'Подобрать без ИИ' })).toHaveCount(0)
  await requestRecommendations(page)
  const cards = page.locator('.release-card')
  await expect(cards.first()).toBeVisible()
  const title = await cards.first().getByRole('heading').innerText()
  const firstTitles = await cards.getByRole('heading').allTextContents()
  await cards.first().getByRole('button', { name: 'Прослушал — нравится', exact: true }).click()
  await expect(cards.first().getByRole('button', { name: 'Прослушал — нравится', exact: true })).toHaveAttribute('aria-pressed', 'true')
  await page.getByRole('button', { name: 'Ещё варианты', exact: true }).click()
  await page.getByRole('button', { name: 'Отправить сообщение' }).click()
  await expect(page.getByText('Ещё варианты', { exact: true }).last()).toBeVisible()
  await expect(page.getByLabel('Сообщение помощнику')).toBeEnabled()
  await requestRecommendations(page, 'Подбери ещё релизы')
  await expect(page.getByLabel('Сообщение помощнику')).toBeEnabled()
  const allTitles = await cards.getByRole('heading').allTextContents()
  expect(new Set(allTitles).size).toBe(allTitles.length)
  expect(allTitles.length).toBeGreaterThan(firstTitles.length)
  const chatId = await page.evaluate(async () => (await (await fetch('/api/chats')).json())[0].id as string)
  const otherContext = await browser.newContext()
  const other = await otherContext.newPage()
  await register(other, 'other')
  expect(await other.evaluate(async () => (await (await fetch('/api/profile')).json()).seed_artist_ids.length)).toBe(0)
  const denied = await other.request.get(`/api/chats/${chatId}`)
  expect(denied.status()).toBe(404)
  await otherContext.close()
  await page.reload()
  await expect(page.getByRole('heading', { name: title, exact: true }).first()).toBeVisible()
  await page.getByRole('button', { name: 'Моя коллекция' }).click()
  await expect(page.getByRole('heading', { name: title, exact: true })).toBeVisible()
  await page.getByRole('button', { name: 'Выйти из аккаунта' }).click()
  await expect(page.getByRole('heading', { name: 'Вход в библиотеку' })).toBeVisible()
  await page.getByLabel('Логин', { exact: true }).fill(username)
  await page.getByLabel('Пароль', { exact: true }).fill(password)
  await page.getByRole('button', { name: 'Войти', exact: true }).click()
  await page.getByRole('button', { name: 'Моя коллекция' }).click()
  await expect(page.getByRole('heading', { name: title, exact: true })).toBeVisible()
})

test('double click and failed response reuse message ID, mobile keyboard and explicit filters', async ({ page }) => {
  await page.setViewportSize({ width: 390, height: 844 })
  await register(page, 'mobile')
  await onboard(page)
  let posted = 0
  const ids: string[] = []
  await page.route('**/api/chats/*/messages', async route => {
    posted += 1; ids.push(route.request().postDataJSON().message_id)
    if (posted === 1) { await route.fetch(); await route.abort('failed') } else await route.continue()
  })
  await page.getByLabel('Сообщение помощнику').fill('Подбери релизы')
  await page.getByRole('button', { name: 'Отправить сообщение' }).evaluate((button: HTMLButtonElement) => { button.click(); button.click() })
  await expect(page.getByRole('button', { name: 'Проверить / повторить тот же запрос' })).toBeVisible()
  expect(posted).toBe(1)
  await page.getByRole('button', { name: 'Проверить / повторить тот же запрос' }).click()
  await expect(page.locator('.release-card').first()).toBeVisible()
  expect(posted).toBe(2); expect(ids[0]).toBe(ids[1])
  await page.getByRole('button', { name: 'Настройки подборки' }).click()
  await page.getByLabel('Насколько неожиданное').selectOption('surprise')
  expect(await page.evaluate(async () => (await (await fetch('/api/chats')).json())[0].filters.mode)).toBe('explore')
  await page.getByRole('button', { name: 'Применить и подобрать' }).click()
  await expect(page.locator('.filter-bar')).toContainText('Более неожиданное')
  await expect(page.getByLabel('Сообщение помощнику')).toBeEnabled()
  expect(await page.evaluate(async () => (await (await fetch('/api/chats')).json())[0].filters.mode)).toBe('surprise')
  await page.getByLabel('Сообщение помощнику').focus()
  await page.keyboard.type('hello')
  await page.keyboard.press('Shift+Enter')
  await expect(page.getByLabel('Сообщение помощнику')).toHaveValue('hello\n')
  await page.keyboard.press('Tab')
  await expect(page.getByRole('button', { name: 'Отправить сообщение' })).toBeFocused()
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= window.innerWidth)).toBe(true)
  await page.screenshot({ path: 'test-results/mobile-discovery.png', fullPage: true })
})

test('personal artist exclusion is confirmed and survives more surprising followup', async ({ page }) => {
  await register(page, 'familiar')
  // Select one favourite artist so the exclusion has a meaningful source.
  await page.getByRole('button', { name: '+ [DEMO] Experimental hip-hop artist 1', exact: true }).click()
  await page.getByRole('button', { name: 'Сохранить вкус и продолжить' }).click()
  await page.getByLabel('Сообщение помощнику').fill('Мне не нужны альбомы тех исполнителей, которых я знаю')
  await page.getByRole('button', { name: 'Отправить сообщение' }).click()
  await expect(page.getByRole('button', { name: 'Применить и подобрать' })).toBeVisible()
  expect(await page.evaluate(async () => (await (await fetch('/api/chats')).json())[0].filters.exclude_known_artists)).toBe(false)
  await page.getByRole('button', { name: 'Применить и подобрать' }).click()
  await expect.poll(async () => page.evaluate(async () => (await (await fetch('/api/chats')).json())[0].filters.exclude_known_artists)).toBe(true)
  await expect(page.locator('.release-card')).toHaveCount(5)
  await page.getByRole('button', { name: 'Более неожиданное', exact: true }).click()
  await page.getByRole('button', { name: 'Отправить сообщение' }).click()
  await expect(page.locator('.release-card')).toHaveCount(10)
  await expect(page.locator('.release-card .artist').filter({ hasText: /^\[DEMO\] Experimental hip-hop artist 1$/ })).toHaveCount(0)
  await page.reload()
  await page.getByRole('button', { name: 'Настройки подборки' }).click()
  await expect(page.getByLabel('Исключать знакомых исполнителей', { exact: true })).toBeChecked()
})

