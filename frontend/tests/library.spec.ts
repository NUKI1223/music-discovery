  await expect(card.getByText('В прослушанных')).toHaveCount(0)
  await page.reload()
  const again = cardOf(page)
  await expect(again.getByRole('button', { name: 'Не по запросу', exact: true })).toHaveAttribute('aria-pressed', 'true')
  await expect(again.getByText('больше не предлагаем для этих жанров')).toBeVisible()
